def build_fdha_lt_xml(selections: dict) -> str:
    """Serialize the 4-slot selection to one NRML logic-tree XML (schema per
    openquake/fdha/logic_tree/nrml_reader.py:24-56).

    All four slots are presented to the user as independent choices. Levels
    1-3 serialize as plain branch sets. At level 4, engine-coupled FD models
    (COUPLED_DISTRIBUTED) are chained to their SR partner with
    applyToBranches, and the remaining FD models are chained to the
    remaining SR branches - applyToBranches matches by set intersection
    (enumerator.py:81-84), so one branch set serves many parents. With no
    coupled model selected the tree is fully flat.
    """
    def branch(ind: str, bid: str, m: dict, weight) -> list[str]:
        body = f"[{m['class_name']}]"
        params = (m.get("params") or "").strip()
        if params:
            body += "\n" + params
        return [
            f'{ind}<logicTreeBranch branchID="{bid}">',
            f"{ind}  <uncertaintyModel><![CDATA[{body}]]></uncertaintyModel>",
            f"{ind}  <uncertaintyWeight>{weight}</uncertaintyWeight>",
            f"{ind}</logicTreeBranch>",
        ]

    parts = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<nrml xmlns="http://openquake.org/xmlns/nrml/0.4">',
        '  <logicTree logicTreeID="lt_fdha_webgui">',
    ]
    # Branch IDs embed the row index so the same model can appear in several
    # branches (with different parameters) without colliding.
    def slot_bids(utype: str, level: int) -> list[str]:
        return [f"{m['class_name'].upper()}_{level}_{j}"
                for j, m in enumerate(selections[utype])]

    plain_levels = ["fdhaPrimarySRModel", "fdhaPrimaryFDModel",
                    "fdhaSecondarySRModel"]
    for i, utype in enumerate(plain_levels, 1):
        slot = REGISTRY["slots"][utype]["package"].rsplit(".", 1)[-1]
        parts.append(f'    <logicTreeBranchingLevel branchingLevelID="bl_{i}_{slot}">')
        parts.append(f'      <logicTreeBranchSet branchSetID="bs_{i}_{slot}"'
                     f' uncertaintyType="{utype}">')
        for bid, m in zip(slot_bids(utype, i), selections[utype]):
            parts += branch("        ", bid, m, m["weight"])
        parts += ["      </logicTreeBranchSet>", "    </logicTreeBranchingLevel>"]

    ssr = selections["fdhaSecondarySRModel"]
    sfd = selections["fdhaSecondaryFDModel"]
    ssr_bids = slot_bids("fdhaSecondarySRModel", 3)
    fd_bids = slot_bids("fdhaSecondaryFDModel", 4)
    free_fd = [(bid, m) for bid, m in zip(fd_bids, sfd)
               if m["class_name"] not in COUPLED_FD_TO_SR]
    coupled_fd = [(bid, m) for bid, m in zip(fd_bids, sfd)
                  if m["class_name"] in COUPLED_FD_TO_SR]
    free_sr_ids = [bid for bid, m in zip(ssr_bids, ssr)
                   if m["class_name"] not in COUPLED_SR_TO_FD]
    # First branch id seen for each coupled SR class, used to chain its
    # FD partner via applyToBranches.
    sr_id_by_class: dict = {}
    for bid, m in zip(ssr_bids, ssr):
        sr_id_by_class.setdefault(m["class_name"], bid)

    parts.append('    <logicTreeBranchingLevel branchingLevelID="bl_4_secondary_surf_displ">')
    if free_fd:
        cond = (f' applyToBranches="{" ".join(free_sr_ids)}"'
                if coupled_fd else "")
        parts.append('      <logicTreeBranchSet branchSetID="bs_4_secondary_surf_displ"'
                     f' uncertaintyType="fdhaSecondaryFDModel"{cond}>')
        for bid, m in free_fd:
            parts += branch("        ", bid, m, m["weight"])
        parts.append("      </logicTreeBranchSet>")
    for j, (bid, m) in enumerate(coupled_fd):
        sr_id = sr_id_by_class.get(COUPLED_FD_TO_SR[m["class_name"]], "")
        parts.append(f'      <logicTreeBranchSet branchSetID="bs_4_{m["class_name"].lower()}_{j}"'
                     f' uncertaintyType="fdhaSecondaryFDModel"'
                     f' applyToBranches="{sr_id}">')
        parts += branch("        ", bid, m, "1.0")
        parts.append("      </logicTreeBranchSet>")
    parts.append("    </logicTreeBranchingLevel>")
    parts += ["  </logicTree>", "</nrml>"]
    return "\n".join(parts)


def engine_validate(xml_text: str):
    """Validate the logic tree with the engine's own parser/validator.

    Returns (errors, warnings, parse_error, environment_error, spec)."""
    import tempfile
    try:
        from openquake.fdha.logic_tree import nrml_reader, validators
        p = Path(tempfile.mkdtemp()) / "fdha_logic_tree.xml"
        p.write_text(xml_text)
        spec = nrml_reader.parse(p)
        report = validators.validate_spec(spec)
        return list(report.errors), list(report.warnings), None, None, spec
    except Exception as exc:  # parse failure
        message = str(exc)
        if "Numba needs NumPy" in message or (
            "NumPy" in message and "Numba" in message
        ):
            return [], [], None, message, None
        return [], [], message, None, None


def build_sm_lt(rows: list[tuple[str, float]]) -> str:
    """Source-model logic tree over (filename, weight) branches - same NRML
    structure as the shipped trees (e.g. config_norcia_case3_iaea_
    source_model_logic_tree.xml)."""
    branches = "\n".join(
        f'      <logicTreeBranch branchID="b_sm_{k}">\n'
        f"        <uncertaintyModel>{fname}</uncertaintyModel>\n"
        f"        <uncertaintyWeight>{w}</uncertaintyWeight>\n"
        "      </logicTreeBranch>"
        for k, (fname, w) in enumerate(rows))
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<nrml xmlns:gml="http://www.opengis.net/gml"\n'
        '      xmlns="http://openquake.org/xmlns/nrml/0.4">\n'
        '  <logicTree logicTreeID="lt_sm_webgui">\n'
        '    <logicTreeBranchSet uncertaintyType="sourceModel"'
        ' branchSetID="bs_sm_webgui">\n'
        f"{branches}\n"
        "    </logicTreeBranchSet>\n"
        "  </logicTree>\n"
        "</nrml>\n")


def parse_sm_lt(xml_text: str) -> list[tuple[str, float]]:
    """List (source-model filename, weight) branches of a source-model
    logic-tree XML (NRML 0.4, uncertaintyType='sourceModel')."""
    ns = {"n": "http://openquake.org/xmlns/nrml/0.4"}
    root = ET.fromstring(xml_text)
    out = []
    for br in root.iter("{http://openquake.org/xmlns/nrml/0.4}logicTreeBranch"):
        um = br.find("n:uncertaintyModel", ns)
        uw = br.find("n:uncertaintyWeight", ns)
        if um is not None and uw is not None:
            out.append((um.text.strip(), float(uw.text)))
    return out


def parse_fault_traces(xml_path: Path) -> list[dict]:
    """Extract simple fault trace paths from an NRML source-model XML."""
    root = ET.parse(xml_path).getroot()
    traces = []
    for elem in root.iter():
        tag = elem.tag.split("}")[-1]
        if not tag.endswith("FaultSource"):
            continue
        pos_text = None
        for child in elem.iter():
            if child.tag.split("}")[-1] == "posList" and child.text:
                pos_text = child.text
                break
        if not pos_text:
            continue
        values = [float(value) for value in pos_text.split()]
        path = [
            [values[index], values[index + 1]]
            for index in range(0, len(values) - 1, 2)
        ]
        if len(path) >= 2:
            traces.append({
                "source_id": elem.get("id") or "source",
                "name": elem.get("name") or elem.get("id") or "source",
                "path": path,
            })
    return traces


def source_model_files_for_run(jobdir: Path) -> list[Path]:
    """Resolve source-model XML files copied into a run directory."""
    sm_lt = jobdir / "source_model_logic_tree.xml"
    if sm_lt.exists():
        try:
            names = [name for name, _ in parse_sm_lt(sm_lt.read_text())]
            files = [jobdir / name for name in names if (jobdir / name).exists()]
            if files:
                return files
        except Exception:
            pass
    return [
        path for path in sorted(jobdir.glob("*.xml"))
        if path.name not in {"fdha_logic_tree.xml", "source_model_logic_tree.xml"}
    ]


def fault_traces_for_run(jobdir: Path) -> list[dict]:
    """Return all fault traces from source models associated with a run."""
    traces = []
    for xml_path in source_model_files_for_run(jobdir):
        try:
            traces.extend(parse_fault_traces(xml_path))
        except Exception:
            continue
    return traces


def map_view_state(points: list[dict], traces: list[dict]):
    """Create a stable PyDeck viewport from points and fault trace vertices."""
    import pydeck as pdk

    coords = [[point["lon"], point["lat"]] for point in points]
    for trace in traces:
        coords.extend(trace["path"])
    if not coords:
        return pdk.ViewState(latitude=0.0, longitude=0.0, zoom=1.0)

    lons = [coord[0] for coord in coords]
    lats = [coord[1] for coord in coords]
    span = max(max(lons) - min(lons), max(lats) - min(lats), 0.001)
    if span < 0.05:
        zoom = 11.0
    elif span < 0.2:
        zoom = 9.5
    elif span < 1.0:
        zoom = 8.0
    else:
        zoom = 5.5
    return pdk.ViewState(
        latitude=sum(lats) / len(lats),
        longitude=sum(lons) / len(lons),
        zoom=zoom,
        pitch=0,
        bearing=0,
    )


def selected_pydeck_object(event, layer_id: str) -> dict | None:
    """Read the first selected object from a Streamlit PyDeck event."""
    if not event:
        return None
    selection = getattr(event, "selection", None)
    if selection is None and isinstance(event, dict):
        selection = event.get("selection")
    if not selection:
        return None
    objects = getattr(selection, "objects", None)
    if objects is None and isinstance(selection, dict):
        objects = selection.get("objects", {})
    selected = (objects or {}).get(layer_id) or []
    return selected[0] if selected else None


