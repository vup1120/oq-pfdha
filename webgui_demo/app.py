def page_run() -> None:
    st.header("Run")
    cfg = st.session_state.get("config")
    if cfg is None:
        st.warning("No configuration yet - visit **1. Configure** first.")
        return

    st.subheader("Job summary")
    c1, c2, c3 = st.columns(3)
    c1.metric("Source model", cfg["source_label"].split(" (")[0])
    c1.metric("Calculation type", cfg["calc_type"].replace("_", " "))
    c2.metric("End-branches", cfg["n_branches"])
    c2.metric("r_threshold_km", f'{cfg["r_threshold_km"]} km')
    c3.metric("rupture_mesh_spacing", f'{cfg["mesh"]} km')
    if cfg["return_period"]:
        c3.metric("return_period", f'{cfg["return_period"]} yr')
    with st.expander("job.ini to be executed"):
        st.code(build_job_ini(cfg), language="ini")

    if not cfg["valid"]:
        st.error("Configuration is incomplete or invalid - fix the issues "
                 "flagged on **1. Configure** before running.")
        return

    est = cfg["n_branches"]
    if est > 8:
        st.warning(f"{est} end-branches - this is a full calculation, not a "
                   "quick demo; it may take many minutes.")

    if st.button("Run calculation", type="primary"):
        stamp = _dt.datetime.now().strftime("%Y%m%d_%H%M%S")
        jobdir = RUNS / f"run_{stamp}"
        outdir = jobdir / "out"
        jobdir.mkdir(parents=True, exist_ok=True)
        for f in cfg["sm_files"]:
            shutil.copy(f, jobdir / Path(f).name)
        (jobdir / "source_model_logic_tree.xml").write_text(cfg["sm_lt_text"])
        (jobdir / "fdha_logic_tree.xml").write_text(cfg["lt_xml"])
        ini = jobdir / "job.ini"
        ini.write_text(build_job_ini(cfg))

        log_buf = io.StringIO()
        handler = logging.StreamHandler(log_buf)
        handler.setLevel(logging.INFO)
        logging.getLogger().addHandler(handler)
        t0 = _dt.datetime.now()
        try:
            with st.status("Running the oq-pfdha engine...", expanded=True) as status:
                st.write(f"Job directory: `{jobdir}`")
                from openquake.fdha.logic_tree.driver import FdhaLogicTree
                result = FdhaLogicTree.from_ini(ini).run(outdir=outdir)
                dt = (_dt.datetime.now() - t0).total_seconds()
                status.update(label=f"Completed in {dt:.1f} s",
                              state="complete")
            st.session_state["last_run"] = {
                "outdir": str(outdir), "jobdir": str(jobdir),
                "mode": result.mode, "elapsed_s": dt,
            }
            st.success(f"Calculation finished ({result.mode}, {dt:.1f} s) - "
                       "see **3. Results**.")
        except Exception:
            st.error("The engine raised an error - full traceback below.")
            st.exception(Exception("engine failure"))
            import traceback
            st.code(traceback.format_exc())
        finally:
            logging.getLogger().removeHandler(handler)
        log_text = log_buf.getvalue().strip()
        if log_text:
            with st.expander("Engine log"):
                st.code(log_text[-8000:])


