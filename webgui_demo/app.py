def list_sources(xml_path: Path) -> list[dict]:
    """Parse an NRML source model and list its fault sources (id/name/rake)."""
    ns = {"n": "http://openquake.org/xmlns/nrml/0.4",
          "n5": "http://openquake.org/xmlns/nrml/0.5"}
    root = ET.parse(xml_path).getroot()
    out = []
    for elem in root.iter():
        tag = elem.tag.split("}")[-1]
        if tag.endswith("FaultSource"):
            rake_el = elem.find(".//n:rake", ns) or elem.find(".//n5:rake", ns)
            rake = float(rake_el.text) if rake_el is not None else None
            style = ""
            if rake is not None:
                # rake -> style classification convention used by the engine
                if -135 <= rake <= -45:
                    style = "normal"
                elif 45 <= rake <= 135:
                    style = "reverse"
                else:
                    style = "strike-slip"
            out.append({"id": elem.get("id"), "name": elem.get("name"),
                        "type": tag, "rake": rake, "style": style})
    return out


