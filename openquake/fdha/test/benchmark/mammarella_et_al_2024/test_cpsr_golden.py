# -*- coding: utf-8 -*-
"""
Benchmark test: Mammarella et al. (2024) CPSR golden outputs

Strict parity test against CPSR.m golden outputs.

Purpose
-------
Validate Mammarella2024PrimarySR against results generated by the authors'
CPSR code. The test consumes a golden CSV placed under expected/ and asserts tight numerical agreement.

Usage
-----
Expected CSV filename: mammarella2024_cpsr.csv

CSV header columns:
- Mw, MSR, style, HDD, Zs_mu, dip_mu, dip_sigma, t_d, Zs_sigma, t_z, expected

If the CSV is absent, the test is skipped.
"""

import csv
import os
import numpy as np
import pytest

pytestmark = pytest.mark.benchmark

from openquake.pfd.primary_surf_rup.mammarella2024 import Mammarella2024PrimarySR


GOLDEN_PATH = os.path.join(
    os.path.dirname(__file__),
    "expected",
    "mammarella2024_cpsr.csv",
)


@pytest.mark.parametrize("tol_abs,tol_rel", [(2e-3, 2e-3)])
def test_against_cpsr_m_golden(tol_abs, tol_rel):
    if not os.path.exists(GOLDEN_PATH):
        pytest.skip(f"CPSR golden file not found: {GOLDEN_PATH}")

    model = Mammarella2024PrimarySR()

    with open(GOLDEN_PATH, "r", newline="") as f:
        reader = csv.DictReader(f)
        rows = list(reader)

    assert rows, "Golden CSV is empty"

    for row in rows:
        Mw = float(row["Mw"])  # scalar
        MSR = int(row["MSR"])  # 0,1,2
        style = row["style"].strip()
        HDD = row["HDD"].strip()
        Zs_mu = float(row["Zs_mu"])  # km
        dip_mu = float(row["dip_mu"])  # deg
        dip_sigma = float(row["dip_sigma"])  # deg
        t_d = float(row["t_d"])  # sigma
        Zs_sigma = float(row["Zs_sigma"])  # km
        t_z = float(row["t_z"])  # sigma
        expected = float(row["expected"])  # CPSR.m output

        p_model = model.get_prob(
            mag=Mw,
            MSR=MSR,
            HDD_str=HDD,
            dip_mu=dip_mu,
            dip_sigma=dip_sigma,
            t_d=t_d,
            Zs_sigma=Zs_sigma,
            t_z=t_z,
            style=style,
            seismothickness=Zs_mu,
        )

        assert np.isfinite(p_model)
        assert p_model == pytest.approx(expected, rel=tol_rel, abs=tol_abs)
